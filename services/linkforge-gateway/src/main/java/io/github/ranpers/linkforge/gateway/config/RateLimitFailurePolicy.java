package io.github.ranpers.linkforge.gateway.config;

/**
 * 令牌桶无法完成判定时，网关对该路由请求的处置方式。
 *
 * @apiNote 策略在装配路由时显式指定，不从路由 ID 推断。路由 ID 只是运维命名，改名不应改变
 * 安全语义，而由字符串推断出的策略在改名后会静默失效。
 * @see GatewayRouteConfiguration
 */
public enum RateLimitFailurePolicy {

    /**
     * 放行。
     *
     * <p>用于选择可用性优先的路由。放行不等于不限流：正常情况下令牌桶照常判定，只是判定无法完成
     * 时不再拦截，因此这些路由要挡的风险在故障期间不再受控。流量洪泛与下游容量对两条放行路由都
     * 成立，短链跳转另有短码枚举风险；元数据路由没有可枚举的秘密，也没有口令爆破面。这里接受该
     * 风险，因为拒绝降级会让路由承载的全部业务同时不可用：跳转失效即全部短链失效，元数据失效会
     * 让资源服务器取不到公钥、OIDC 客户端无法完成服务发现，等于把一次存储故障放大成认证生态故障。</p>
     */
    ALLOW,

    /**
     * 拒绝并返回 503。
     *
     * <p>用于一旦失去限流就会扩大攻击面或资源消耗的路由：口令爆破、批量写入、权限探测、
     * 资源滥用与管理接口流量失控都属此类。这些接口都要过认证与权限校验且含写操作，客户端通常
     * 可以安全重试，因此相比短时降低可用性，失去它们的请求保护是更不可接受的风险。
     * 返回 503 而不是 429，是因为判定没有完成，没有资格声称对方超出配额。</p>
     */
    REJECT
}
