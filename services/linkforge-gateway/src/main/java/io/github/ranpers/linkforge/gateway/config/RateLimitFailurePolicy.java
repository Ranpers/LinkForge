package io.github.ranpers.linkforge.gateway.config;

/**
 * 令牌桶无法完成判定时，网关对该路由请求的处置方式。
 *
 * @apiNote 策略在装配路由时显式指定，不从路由 ID 推断。路由 ID 只是运维命名，改名不应改变
 * 安全语义，而由字符串推断出的策略在改名后会静默失效。
 * @see GatewayRouteConfiguration
 */
public enum RateLimitFailurePolicy {

    /**
     * 放行。
     *
     * <p>用于选择可用性优先的路由。这些路由同样有限流要挡的风险，例如流量洪泛、枚举与下游
     * 容量，放行即意味着这些风险在故障期间不再受控；这里接受该风险，因为拒绝降级会让路由
     * 承载的全部业务同时不可用。</p>
     */
    ALLOW,

    /**
     * 拒绝并返回 503。
     *
     * <p>用于一旦失去限流就会暴露口令爆破或越权尝试面的路由。相比短时降低可用性，
     * 失去这些接口的请求保护是更不可接受的风险；返回 503 而不是 429，是因为判定没有完成，
     * 没有资格声称对方超出配额。</p>
     */
    REJECT
}
